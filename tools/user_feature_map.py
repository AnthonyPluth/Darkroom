from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
REFERENCES = ".claude/skills/verify-darkroom/references"
OUT = ROOT / REFERENCES / "feature-map.md"
GOTCHAS = ROOT / REFERENCES / "feature-gotchas.md"
VIEWPORT_ORDER = ["phone", "desktop", "laptop", "wide"]


def exported_list(text: str, name: str) -> list[str]:
    found = re.search(rf"export const {name} = \[(.*?)\];", text, re.DOTALL)
    return re.findall(r'"([^"]+)"', found.group(1)) if found else []


def routes(text: str) -> dict[str, str]:
    found = re.search(r"export const ROUTES = \{(.*?)\};", text, re.DOTALL)
    return dict(re.findall(r'"?([\w-]+)"?:\s*"([^"]+)"', found.group(1))) if found else {}


def nav_labels(nav: str) -> dict[str, str]:
    return {path: label for path, label in re.findall(r'\{ path: "([^"]+)", label: "([^"]+)" \}', nav)}


def flows(directory: Path) -> list[dict]:
    return [json.loads(p.read_text()) for p in sorted(directory.glob("*.json"))]


def gotchas(text: str, names: set[str]) -> tuple[dict[str, list[str]], list[str]]:
    out: dict[str, list[str]] = {}
    problems = []
    current = None
    for line in text.splitlines():
        if line.startswith("## "):
            current = line[3:].strip()
            if current not in names:
                problems.append(f"feature-gotchas.md: `## {current}` is not a page or flow name")
            elif current in out:
                problems.append(f"feature-gotchas.md: `## {current}` appears twice")
            out.setdefault(current, [])
        elif line.startswith("- ") and current:
            out[current].append(line[2:].strip())
        elif current is None:
            continue
        elif line.strip() and not line.startswith(("- ", "  ")):
            problems.append(f"feature-gotchas.md: only `- ` bullets go under a heading: {line[:50]!r}")
    return out, problems


def uniq(items: list[str]) -> list[str]:
    return list(dict.fromkeys(items))


def code(items: list[str]) -> str:
    return ", ".join(f"`{i}`" for i in items)


def widths(flow: dict) -> list[str]:
    chosen = flow.get("viewports") or ["phone", "desktop"]
    return sorted(chosen, key=lambda v: VIEWPORT_ORDER.index(v) if v in VIEWPORT_ORDER else 99)


def summary(flow: dict) -> dict[str, list[str]]:
    routes_to, clicks, texts, other = [], [], [], []
    for step in flow["steps"]:
        if "goto" in step:
            routes_to.append(step["goto"])
        for key in ("click", "click_if_present", "hover", "fill", "press"):
            if key in step:
                target = step[key]["selector"] if isinstance(step[key], dict) else step[key]
                clicks.append(target)
        if "expect_text" in step:
            texts.append(step["expect_text"]["text"])
        if "sign_out" in step:
            other.append("sign_out")
    return {"goes to": uniq(routes_to), "touches": uniq(clicks), "expects to see": uniq(texts), "signs out": uniq(other)}


def flow_lines(flow: dict, notes: dict[str, list[str]]) -> list[str]:
    name = flow["name"]
    s = summary(flow)
    lines = [f"#### `{name}`", "", f"- **Starts at:** `{flow.get('page', 'status')}`" + (f"; goes to: {code(s['goes to'])}" if s["goes to"] else "") + ".",
             f"- **Widths:** {', '.join(widths(flow))}."]
    if s["touches"]:
        lines.append(f"- **Touches:** {code(s['touches'])}.")
    if s["expects to see"]:
        lines.append(f"- **Expects to see:** {code(s['expects to see'])}.")
    if s["signs out"]:
        lines.append("- **Signs the demo member out** (`sign_out`): what follows is the sign-in page.")
    if flow.get("allow_console"):
        lines.append(f"- **Console errors it expects:** {code(flow['allow_console'])}.")
    lines.append(f"- **Drive it:** `tools/control flow {name}`; or `poetry run python tools/verify.py run --flow {name}`.")
    if notes.get(name):
        lines += ["- **What usually breaks:**", *[f"  - {n}" for n in notes[name]]]
    lines.append("")
    return lines


def render(page_names: list[str], paths: dict[str, str], labels: dict[str, str], signed_out: list[str], all_flows: list[dict],
           notes: dict[str, list[str]]) -> str:
    lines = [
        "# User feature map",
        "",
        "Generated by `tools/user_feature_map.py` (`make user-feature-map`); do not edit. The gotchas come from "
        "[feature-gotchas.md](feature-gotchas.md), which is hand-edited. `make fleet-checks` fails when this file is out of date.",
        "",
        "What a person can do in the web app, by page: how to reach it, how to drive it with `tools/control` (or `make verify`), and what "
        "usually breaks. It is not `docs/feature-map.json`, which goes by API route to find the code behind a feature: this one starts from "
        "what a user sees, from the pages and flows `make verify` runs, and ends at the commands that drive it. All of it is demo data; "
        "`tools/control start` first, and `flow <name>` runs a flow's steps (after `reset` for the data `make verify` starts it from).",
        "",
    ]
    for page in page_names:
        path = paths.get(page, f"/{page}")
        label = labels.get(path, page)
        reach = "the browser signed out, at `/`" if page in signed_out else f"the navigation's {labels[path]}, at `{path}`" if path in labels else f"`{path}`"
        lines += [f"## {label} (`{page}`)", "", f"- **Reach it:** {reach}; control `tools/control goto {page}`.",
                  f"- **Drive it:** `tools/control goto {page}`, `tools/control snapshot --text`, then `click`/`type`/`press`; "
                  f"`tools/control viewport phone|desktop`; batch check `make verify PAGES=\"{page}\"`."]
        if notes.get(page):
            lines += ["- **What usually breaks:**", *[f"  - {n}" for n in notes[page]]]
        mine = [f for f in all_flows if f.get("page", "status") == page]
        lines.append("")
        if mine:
            lines += [f"### Flows on {label}", ""]
        for flow in mine:
            lines += flow_lines(flow, notes)
    return "\n".join(lines).rstrip() + "\n"


def generate(root: Path = ROOT) -> tuple[str, list[str]]:
    verify = (root / "frontend/verify/verify.mjs").read_text()
    route_file = (root / "frontend/verify/routes.mjs").read_text()
    nav = (root / "frontend/src/lib/nav.svelte.ts").read_text()
    page_names = exported_list(verify, "PAGES")
    all_flows = flows(root / "frontend/verify/flows")
    names = set(page_names) | {f["name"] for f in all_flows}
    gotcha_file = root / REFERENCES / "feature-gotchas.md"
    notes, problems = gotchas(gotcha_file.read_text() if gotcha_file.exists() else "", names)
    if not page_names:
        problems.append("no PAGES found in frontend/verify/verify.mjs")
    text = render(page_names, routes(route_file), nav_labels(nav), exported_list(route_file, "SIGNED_OUT_PAGES"), all_flows, notes)
    return text, problems


def check(committed: str | None, generated: str) -> list[str]:
    name = str(OUT.relative_to(ROOT))
    if committed is None:
        return [f"{name}: missing; run make user-feature-map and commit it"]
    if committed != generated:
        return [f"{name} isn't what tools/user_feature_map.py generates: run make user-feature-map and commit the result "
                "(hand-written advice goes in references/feature-gotchas.md, never in the generated file)"]
    return []


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true", help="write nothing; fail when the committed file is out of date")
    args = ap.parse_args(argv)
    text, problems = generate()
    if not args.check and not problems:
        OUT.write_text(text)
    if args.check:
        problems += check(OUT.read_text() if OUT.exists() else None, text)
    for p in problems:
        print(p, file=sys.stderr)
    return 1 if problems else 0


if __name__ == "__main__":
    sys.exit(main())
