describe("qrMatrix", () => {
  it("draws a short text as version 1 at level M, module for module as a reference encoder does", () => {
    expect(drawn(qrMatrix("hello", 0))).toEqual(HELLO_MASK_0);
  });

  it("draws a Syncthing device ID as version 5, module for module as a reference encoder does", () => {
    expect(drawn(qrMatrix(SYNCTHING_DOCS_EXAMPLE_ID, 3))).toEqual(SYNCTHING_DOCS_EXAMPLE_MASK_3);
  });

  it("chooses a mask by itself and keeps the finder patterns in three corners", () => {
    const matrix = qrMatrix(SYNCTHING_DOCS_EXAMPLE_ID);
    const size = matrix.length;
    expect(size).toBe(37);
    const finder = ["#######", "#.....#", "#.###.#", "#.###.#", "#.###.#", "#.....#", "#######"];
    const corner = (x: number, y: number) => drawn(matrix).slice(y, y + 7).map((row) => row.slice(x, x + 7));
    expect(corner(0, 0)).toEqual(finder);
    expect(corner(size - 7, 0)).toEqual(finder);
    expect(corner(0, size - 7)).toEqual(finder);
  });

  it("grows the version with the text and draws version information from version 7", () => {
    expect(qrMatrix("x".repeat(120)).length).toBe(4 * 7 + 17);
    expect(qrMatrix("x".repeat(200)).length).toBe(4 * 10 + 17);
  });

  it("refuses a text too long for the versions it draws", () => {
    expect(() => qrMatrix("x".repeat(300))).toThrow(RangeError);
  });
});
